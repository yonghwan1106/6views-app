/** 시드의 citation 정보를 Citation 타입으로 변환(documentIndex는 문서 등장 순서로 부여) */
function toCitations(
  seedCitations: { citedText: string; documentTitle: string }[],
  docIndexMap: Map<string, number>,
): Citation[] {
  return seedCitations.map((c) => ({
    citedText: c.citedText,
    documentTitle: c.documentTitle,
    documentIndex: docIndexMap.get(c.documentTitle) ?? 0,
  }));
}

/**
 * USE_MOCK 모드에서 사용할 6 증언자 모의 증언을 반환한다.
 * claim 인자는 실제 호출과 시그니처를 맞추기 위한 것으로, 모의 증언 본문은 의제별 고정 시드를 사용한다.
 */
export function getMockTestimonies(agendaId: AgendaId, _claim: string): Testimony[] {
  void _claim; // 모의 모드는 의제별 고정 시드 사용 — claim은 시그니처 일치용
  const seeds = MOCK_SEEDS[agendaId];

  // 의제의 6 증언자(핵심 4 + 동적 2)와 그 시드를 함께 수집한다.
  // MOCK_SEEDS는 의제별로 정확히 6명을 채우므로 모든 시드가 존재한다.
  const entries = witnessIdsForAgenda(agendaId)
    .map((id) => ({ id, seed: seeds[id] }))
    .filter((e): e is { id: WitnessId; seed: MockTestimonySeed } => e.seed !== undefined);

  // 의제 내 등장하는 문서 제목에 인덱스를 부여(citations의 documentIndex 일관성용)
  const docIndexMap = new Map<string, number>();
  for (const { seed } of entries) {
    for (const c of seed.citations) {
      if (!docIndexMap.has(c.documentTitle)) {
        docIndexMap.set(c.documentTitle, docIndexMap.size);
      }
    }
  }

  return entries.map(({ id, seed }) => {
    const meta = WITNESS_META[id];
    const citations = toCitations(seed.citations, docIndexMap);
    return {
      witnessId: id,
      witnessName: meta.name,
      tier: meta.tier,
      stance: seed.stance,
      segments: [{ text: seed.text, citations }],
      citationCount: citations.length,
      // 인용한 고유 문서 종 수
      dataTypesUsed: new Set(citations.map((c) => c.documentTitle)).size,
    };
  });
}
