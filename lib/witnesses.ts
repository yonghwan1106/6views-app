/**
 * 의제에 참여하는 6 증언자(핵심 4 + 동적 2)를 조립한다.
 * WITNESS_META(이름·역할·tier·model·색상) + SYSTEM_PROMPTS(시스템 프롬프트)를 합쳐 Witness[] 반환.
 */
export function getWitnessesForAgenda(agendaId: AgendaId): Witness[] {
  return witnessIdsForAgenda(agendaId).map((id) => {
    const meta = WITNESS_META[id];
    return {
      id,
      name: meta.name,
      role: meta.role,
      tier: meta.tier,
      model: meta.model,
      accentColor: meta.accentColor,
      systemPrompt: SYSTEM_PROMPTS[id],
    };
  });
}
